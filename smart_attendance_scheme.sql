 allowed_radius_meters INTEGER NOT NULL DEFAULT 100
   CHECK (allowed_radius_meters BETWEEN 10 AND 1000),
 status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE class_schedules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_section_id BIGINT NOT NULL REFERENCES class_sections(id) ON DELETE RESTRICT,
 classroom_id BIGINT NOT NULL REFERENCES classrooms(id) ON DELETE RESTRICT,
 day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
 start_time TIME NOT NULL, end_time TIME NOT NULL,
 effective_from DATE, effective_until DATE,
 CHECK (end_time > start_time),
 CHECK (effective_until IS NULL OR effective_from IS NULL OR effective_until >= effective_from),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE attendance_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_section_id BIGINT NOT NULL REFERENCES class_sections(id) ON DELETE RESTRICT,
 class_schedule_id BIGINT REFERENCES class_schedules(id) ON DELETE RESTRICT,
 teacher_id BIGINT NOT NULL REFERENCES teachers(id) ON DELETE RESTRICT,
 classroom_id BIGINT NOT NULL REFERENCES classrooms(id) ON DELETE RESTRICT,
 session_date DATE NOT NULL,
 starts_at TIMESTAMPTZ NOT NULL, late_after TIMESTAMPTZ NOT NULL,
 closes_at TIMESTAMPTZ NOT NULL, closed_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL DEFAULT 'scheduled'
   CHECK (status IN ('scheduled','open','closed','cancelled')),
 -- Snapshot geofence: classroom changes must not rewrite past check-in rules.
 allowed_latitude NUMERIC(10,7) NOT NULL CHECK (allowed_latitude BETWEEN -90 AND 90),
 allowed_longitude NUMERIC(10,7) NOT NULL CHECK (allowed_longitude BETWEEN -180 AND 180),
 allowed_radius_meters INTEGER NOT NULL CHECK (allowed_radius_meters BETWEEN 10 AND 1000),
 CHECK (starts_at <= late_after AND late_after <= closes_at),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE attendance_qr_tokens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 attendance_session_id BIGINT NOT NULL REFERENCES attendance_sessions(id) ON DELETE CASCADE,
 token_hash CHAR(64) NOT NULL UNIQUE, -- SHA-256 hex of unpredictable token
 expires_at TIMESTAMPTZ NOT NULL, revoked_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CHECK (expires_at > created_at)
);
CREATE TABLE attendances (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 attendance_session_id BIGINT NOT NULL REFERENCES attendance_sessions(id) ON DELETE RESTRICT,
 student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
 status VARCHAR(20) NOT NULL CHECK (status IN ('present','late','absent','excused')),
 verification_method VARCHAR(30) NOT NULL
   CHECK (verification_method IN ('dynamic_qr','manual','system')),
 -- For absent/manual records GPS & check-in time can be NULL.
 latitude NUMERIC(10,7) CHECK (latitude BETWEEN -90 AND 90),
 longitude NUMERIC(10,7) CHECK (longitude BETWEEN -180 AND 180),
 gps_accuracy_meters NUMERIC(8,2) CHECK (gps_accuracy_meters >= 0),
 distance_meters NUMERIC(10,2) CHECK (distance_meters >= 0),
 checked_in_at TIMESTAMPTZ, marked_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
 remarks TEXT,
 UNIQUE(attendance_session_id,student_id),
 CHECK (verification_method <> 'dynamic_qr' OR
   (status IN ('present','late') AND checked_in_at IS NOT NULL AND
    latitude IS NOT NULL AND longitude IS NOT NULL AND
    gps_accuracy_meters IS NOT NULL AND distance_meters IS NOT NULL)),
 CHECK (verification_method <> 'system' OR status = 'absent'),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE attendance_corrections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 attendance_id BIGINT NOT NULL REFERENCES attendances(id) ON DELETE RESTRICT,
 requested_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 reviewed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
 reason TEXT NOT NULL,
 requested_status VARCHAR(20) NOT NULL
   CHECK (requested_status IN ('present','late','absent','excused')),
 status VARCHAR(20) NOT NULL DEFAULT 'pending'
   CHECK (status IN ('pending','approved','rejected')),
 reviewed_at TIMESTAMPTZ, review_note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 title VARCHAR(150) NOT NULL, message TEXT NOT NULL,
 type VARCHAR(50) NOT NULL, data JSONB, read_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
 action VARCHAR(100) NOT NULL, entity_type VARCHAR(100) NOT NULL,
 entity_id BIGINT, old_values JSONB, new_values JSONB,
 ip_address INET, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

